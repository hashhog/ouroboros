# Sanity: every vector must be the right shape.
@pytest.mark.parametrize("vec", BIP324_XDH_VECTORS, ids=lambda v: v["shared_secret"][:16])
def test_vector_shape(vec: dict[str, object]) -> None:
    assert len(bytes.fromhex(vec["priv_ours"])) == 32
    assert len(bytes.fromhex(vec["ellswift_ours"])) == 64
    assert len(bytes.fromhex(vec["ellswift_theirs"])) == 64
    assert len(bytes.fromhex(vec["shared_secret"])) == 32


# The actual byte-for-byte check: 7/7 must agree with libsecp256k1.
@pytest.mark.parametrize(
    "vec_index",
    range(len(BIP324_XDH_VECTORS)),
    ids=[f"vec{i}" for i in range(len(BIP324_XDH_VECTORS))],
)
def test_ellswift_xdh_matches_libsecp256k1_reference(vec_index: int) -> None:
    """Each vector: feed our ``secp256k1_ellswift_xdh`` wrapper the same
    inputs libsecp256k1 uses internally; the output must match
    bit-for-bit.  This is the test camlcoin's wiring uses to lock down
    its own ctypes binding — see camlcoin/lib/schnorr_stubs.c (commit
    559c3d1) for the C-side analog."""
    vec = BIP324_XDH_VECTORS[vec_index]
    priv = bytes.fromhex(vec["priv_ours"])
    ours = bytes.fromhex(vec["ellswift_ours"])
    theirs = bytes.fromhex(vec["ellswift_theirs"])
    initiating = vec["initiating"]
    expected = bytes.fromhex(vec["shared_secret"])

    got = secp256k1_ellswift_xdh(ours, theirs, priv, initiating)
    assert got == expected, (
        f"BIP 324 XDH vector {vec_index} mismatch: "
        f"got={got.hex()} expected={expected.hex()}"
    )


def test_ellswift_xdh_all_seven_vectors_pass() -> None:
    """Aggregate counter for the report: how many of the 7 reference
    vectors pass byte-for-byte."""
    passed = 0
    for vec in BIP324_XDH_VECTORS:
        priv = bytes.fromhex(vec["priv_ours"])
        ours = bytes.fromhex(vec["ellswift_ours"])
        theirs = bytes.fromhex(vec["ellswift_theirs"])
        initiating = vec["initiating"]
        expected = bytes.fromhex(vec["shared_secret"])
        got = secp256k1_ellswift_xdh(ours, theirs, priv, initiating)
        if got == expected:
            passed += 1
    assert passed == len(BIP324_XDH_VECTORS), (
        f"Only {passed}/{len(BIP324_XDH_VECTORS)} BIP 324 vectors passed"
    )


def test_ellswift_create_then_xdh_self_pair() -> None:
    """End-to-end check using the full ``secp256k1_ellswift_create`` /
    ``secp256k1_ellswift_xdh`` round-trip rather than canned encodings:
    if both sides each generate a real keypair, exchange ellswift
    pubkeys, and run the XDH hash with party=0/1 — they must arrive at
    the same shared secret.  This is the actual code path the v2
    handshake takes."""
    import os
    init_priv = os.urandom(32)
    resp_priv = os.urandom(32)
    init_aux = os.urandom(32)
    resp_aux = os.urandom(32)

    init_pub = secp256k1_ellswift_create(init_priv, init_aux)
    resp_pub = secp256k1_ellswift_create(resp_priv, resp_aux)
    assert len(init_pub) == 64
    assert len(resp_pub) == 64

    init_secret = secp256k1_ellswift_xdh(
        ell_ours=init_pub, ell_theirs=resp_pub,
        secret_key=init_priv, initiating=True,
    )
    resp_secret = secp256k1_ellswift_xdh(
        ell_ours=resp_pub, ell_theirs=init_pub,
        secret_key=resp_priv, initiating=False,
    )
    assert init_secret == resp_secret, (
        "ECDH symmetry failure: initiator and responder derived "
        "different secrets from a fresh ellswift keypair"
    )
    assert len(init_secret) == 32


def test_v2handshake_uses_real_ecdh() -> None:
    """``V2Handshake`` should now drive the real ellswift+xdh path, so
    its ``_shared_secret`` agrees between initiator and responder for
    a fresh self-pair.  (Was previously a sorted-key hash —
    self-consistent but not real ECDH.)"""
    initiator = V2Handshake(initiator=True)
    responder = V2Handshake(initiator=False)
    initiator.receive_remote_pubkey(responder.local_pubkey_bytes)
    responder.receive_remote_pubkey(initiator.local_pubkey_bytes)
    assert initiator._shared_secret is not None
    assert initiator._shared_secret == responder._shared_secret
    assert len(initiator._shared_secret) == 32

    # And the local pubkeys must be 64 bytes each (real ellswift output,
    # not a hash concatenation).
    assert len(initiator.local_pubkey_bytes) == 64
    assert len(responder.local_pubkey_bytes) == 64
    # Two fresh handshakes must produce different ephemeral pubkeys.
    other = V2Handshake(initiator=True)
    assert other.local_pubkey_bytes != initiator.local_pubkey_bytes
