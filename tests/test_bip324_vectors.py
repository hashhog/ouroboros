"""Byte-for-byte validation of BIP 324 ECDH against libsecp256k1's
reference vectors.

These vectors were generated by an independent implementation and
cross-verified against the BIP 324 paper authors' decoding code; they
are the canonical test data for ``secp256k1_ellswift_xdh`` with the
BIP 324 hash function.  Source:

    bitcoin-core/src/secp256k1/src/modules/ellswift/tests_impl.h:156-164
    (struct ellswift_xdh_test ellswift_xdh_tests_bip324[])

Same 7-vector table that camlcoin's BIP 324 wiring (commit 559c3d1)
validates its ctypes bindings against.

A pass here means ouroboros's V2 handshake, when given matching
inputs, produces the same 32-byte shared secret as Bitcoin Core's
reference libsecp256k1.  This is the prerequisite for v2 interop with
Core — without it, the cipher's ECDH is a self-consistent toy.

NOTE on scope: passing these vectors does NOT yet imply full BIP 324
wire-format interop with Core.  The session-key expansion,
length-cipher derivation, and garbage-terminator schedule are still
the simplified one-key-per-direction layout from the original
``transport_v2`` cipher.  That's tracked as the next NEEDS-INFRA
upgrade; this test pins the ECDH layer so it never regresses.
"""

